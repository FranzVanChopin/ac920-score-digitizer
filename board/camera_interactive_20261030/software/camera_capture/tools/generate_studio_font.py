"""Generate the renamed Studio UI ASCII raster font from installed Noto Sans SC.

Runtime needs no font file, allocator or Python. Generator needs Pillow only.
Glyph bitmaps retain SIL OFL1.1; renderer C is MIT. Source SHA pins regeneration.
"""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont

SOURCE_SHA='763146584cf0710223441356b4395e279021b0806c196614377a7a0174ae074a'
SIZES=(12,18,24,34)
WEIGHTS=(400,400,400,500)
DEFAULT=Path('C:/Windows/Fonts/NotoSansSC-VF.ttf')
ROOT=Path(__file__).resolve().parents[1]


def make(source):
    source=Path(source)
    digest=hashlib.sha256(source.read_bytes()).hexdigest()
    if digest!=SOURCE_SHA:raise ValueError('Source font SHA differs; supply the pinned font file')
    data=bytearray();tables=[]
    for pixels,weight in zip(SIZES,WEIGHTS):
        font=ImageFont.truetype(str(source),pixels)
        font.set_variation_by_axes([weight])
        cap=-font.getbbox('H',anchor='ls')[1]
        table=[]
        for code in range(32,127):
            char=chr(code);left,top,right,bottom=font.getbbox(char,anchor='ls')
            width,height=right-left,bottom-top
            advance=max(1,round(font.getlength(char)))
            if code==32:width=height=0
            assert max(width,height,advance)<256
            assert -128<=left<128 and -128<=cap+top<128
            image=Image.new('L',(max(1,width),max(1,height)))
            if width and height:
                ImageDraw.Draw(image).text((-left,-top),char,font=font,fill=255,anchor='ls')
            alpha=[(v+8)//17 for v in image.tobytes()[:width*height]]
            offset=len(data)
            for at in range(0,len(alpha),2):
                data.append((alpha[at]<<4)|(alpha[at+1] if at+1<len(alpha) else 0))
            table.append((offset,width,height,left,cap+top,advance))
        tables.append(table)
    assert len(data)<200000
    lines=['/* Generated by tools/generate_studio_font.py; do not edit glyphs. */',
           '/* Renderer code: SPDX-License-Identifier: MIT. Glyphs: SIL OFL1.1. */',
           '/* Font source '+digest+'; see STUDIO_FONT_OFL.txt. */',
           '#include "studio_font.h"','#include <limits.h>',
           'typedef struct {uint32_t offset;uint8_t width,height;int8_t x,y;uint8_t advance;} studio_glyph;',
           'static const uint8_t studio_alpha[] = {']
    for at in range(0,len(data),24):lines.append('    '+','.join('0x%02x'%v for v in data[at:at+24])+',')
    lines.append('};\nstatic const studio_glyph studio_glyphs[4][95] = {')
    for table in tables:
        lines.append('  {')
        lines.extend('    {%u,%u,%u,%d,%d,%u},'%record for record in table)
        lines.append('  },')
    lines.append('};\n')
    lines.append(RENDERER)
    (ROOT/'studio_font.c').write_text('\n'.join(lines),encoding='utf-8',newline='\n')
    notice='''Studio UI font: static anti-aliased ASCII raster subset,12/18/24/34px.

Source family: Noto Sans SC variable font (not Apple SF/San Francisco).
Origin used: C:/Windows/Fonts/NotoSansSC-VF.ttf
Source SHA256: %s
Upstream source: https://github.com/google/fonts/tree/main/ofl/notosanssc
Upstream licensing: https://raw.githubusercontent.com/google/fonts/main/ofl/notosanssc/OFL.txt
Copyright2014-2021 Adobe (http://www.adobe.com/), Reserved Font Name 'Source'.
Glyph assets retain SIL Open Font License1.1; see STUDIO_FONT_OFL.txt.
The modified raster subset's primary name is Studio UI. No Apple font is used.
The C drawing implementation is MIT.

Regenerate: python tools/generate_studio_font.py --font <pinned TTF path>
Pillow performs the rasterization. The generator checks the exact source hash;
use the same source file to reproduce the bytes. Other machines can supply a
copy of that source file, which remains subject to its upstream OFL license.
Runtime: only studio_font.c/h are needed, without TTF/Pillow or heap allocation.
Sizes:12,18,24,34px; weights400,400,400,500;4-bit antialias alpha.
Compiled glyph alpha:%u bytes; glyph table380 compact records.
'''%(digest,len(data))
    (ROOT/'STUDIO_FONT_SOURCE.txt').write_text(notice,encoding='utf-8',newline='\n')
    print(json.dumps(dict(alpha_bytes=len(data),glyphs=380,sizes=SIZES,source_sha256=digest)))


RENDERER=r'''
unsigned studio_font_measure(const char *text,unsigned scale)
{
    unsigned total=0;
    if(!text || scale<1u || scale>4u) return 0;
    for(;*text;++text) {
        unsigned c=(unsigned char)*text,advance;
        if(c<32u || c>126u) continue;
        advance=studio_glyphs[scale-1u][c-32u].advance;
        if(total>UINT_MAX-advance) return UINT_MAX;
        total+=advance;
    }
    return total;
}

void studio_font_text(uint8_t *dst,unsigned w,unsigned h,size_t stride,
                      unsigned x,unsigned y,const char *text,unsigned scale,uint32_t rgb)
{
    unsigned pen=x;
    uint8_t ink[3]={(uint8_t)rgb,(uint8_t)(rgb>>8),(uint8_t)(rgb>>16)};
    if(!dst || !text || !w || !h || w>8192u || h>8192u ||
       scale<1u || scale>4u || x>=w || y>=h || stride<(size_t)w*3u ||
       stride>SIZE_MAX/h || (uintptr_t)dst>UINTPTR_MAX-stride*h) return;
    for(;*text && pen<w;++text) {
        unsigned c=(unsigned char)*text,row,col;
        const studio_glyph *g;
        if(c<32u || c>126u) continue;
        g=&studio_glyphs[scale-1u][c-32u];
        for(row=0;row<g->height;++row) {
            int dy=(int)y+g->y+(int)row;
            if(dy<0 || (unsigned)dy>=h) continue;
            for(col=0;col<g->width;++col) {
                int dx=(int)pen+g->x+(int)col;
                unsigned at=row*g->width+col,a;
                uint8_t *pixel;
                if(dx<0 || (unsigned)dx>=w) continue;
                a=studio_alpha[g->offset+at/2u];a=(at&1u)?(a&15u):(a>>4u);
                if(!a) continue;
                pixel=dst+(size_t)(unsigned)dy*stride+(size_t)(unsigned)dx*3u;
                pixel[0]=(uint8_t)((pixel[0]*(15u-a)+ink[0]*a+7u)/15u);
                pixel[1]=(uint8_t)((pixel[1]*(15u-a)+ink[1]*a+7u)/15u);
                pixel[2]=(uint8_t)((pixel[2]*(15u-a)+ink[2]*a+7u)/15u);
            }
        }
        /* pen<=8191 and advance<=255, so this addition cannot overflow. */
        pen+=g->advance;
    }
}
'''

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--font',type=Path,default=DEFAULT)
    args=parser.parse_args();make(args.font)
