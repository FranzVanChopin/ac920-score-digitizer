"""Local image-certified count recovery; unchanged measures retain their XML.

No target bar count, reference score or page identifier enters inference.
The two supported edits are an anchored missing musical bar and a duplicate
terminal chord generated by a trailing key signature. Ambiguity abstains.
"""
from collections import Counter
from fractions import Fraction
import copy, hashlib
from pathlib import Path
import xml.etree.ElementTree as E
import cv2
import numpy as np
from omr_event_records import records
from .testset3_staff_resize_fast import resize_staves
from .symbol_cnn import FACTOR


def systems(root):
    result=[[]]
    for i,m in enumerate(root.findall('part/measure')):
        if i and any(p.get('new-system')=='yes' for p in m.findall('print')):result.append([])
        result[-1].append(m)
    return result


def signature(row):return Counter(r['key'] for r in row if not r['grace'])


def insertion_sites(left,right):
    if len(right)!=len(left)+1 or len(right)>128:return []
    return [i for i in range(1,len(right)-1) if left==right[:i]+right[i+1:]]


def pitches(row,written=False):
    return Counter((r['staff'],r['node'].findtext('pitch/step'),r['node'].findtext('pitch/octave')) if written else (r['staff'],r['midi']) for r in row if r['midi'] is not None and not r['grace'])


def crossing(image,track,x):
    s=track['space_px'];ys=np.array([np.interp(x,*np.asarray(l['polyline']).T) for l in (track['lines'][0],track['lines'][-1])])
    yy=np.linspace(ys[0]+.15*s,ys[1]-.15*s,64).astype('float32')[:,None]
    xx=np.linspace(x-.4*s,x+.4*s,round(.8*s)+1).astype('float32')[None]
    q=cv2.remap((image<155).astype('uint8'),np.broadcast_to(xx,(64,xx.shape[1])).copy(),np.broadcast_to(yy,(64,xx.shape[1])).copy(),cv2.INTER_NEAREST)
    return float(q.mean(0).max())


def repair(root,other,graph,photo,geometry):
    if len(root.findall('part'))!=1 or len(other.findall('part'))!=1:return []
    bm=root.findall('part/measure');cm=other.findall('part/measure')
    if abs(len(bm)-len(cm))!=1:return []
    bs=systems(root);ids=sorted({r['system'] for r in graph['systems']})
    if not 1<=len(ids)<=64 or len(bs)!=len(ids):return []
    if len(graph.get('stems',[]))>4096 or len(graph['systems'])>128:return []
    sizes=[len(next(r for r in graph['systems'] if r['system']==sid)['bounds'])-1 for sid in ids]
    if sum(sizes)!=len(cm) or any(n>128 for n in sizes):return []
    cs=[];offset=0
    for size in sizes:cs.append(cm[offset:offset+size]);offset+=size
    affected=[i for i,(a,b) in enumerate(zip(bs,cs)) if len(a)!=len(b)]
    if len(affected)!=1:return []
    digest=hashlib.sha256(Path(photo).read_bytes()).hexdigest()
    if graph.get('image_sha256')!=digest or geometry.get('image_sha256')!=digest:raise ValueError('Bar repair photo mismatch')
    raw=cv2.imread(str(photo),0)
    if raw is None or raw.size>16000000 or max(raw.shape)>8192:return []
    if geometry['image_size_px']!=[raw.shape[1],raw.shape[0]]:raise ValueError('Bar repair geometry size mismatch')
    image=cv2.resize(raw,None,fx=FACTOR,fy=FACTOR,interpolation=cv2.INTER_AREA);del raw
    tracks=resize_staves(geometry['staves'],FACTOR,FACTOR);i=affected[0];sid=ids[i]
    rows=[r for r in graph['systems'] if r['system']==sid];ts=[t for t in tracks if t['system']==sid]
    if len(ts)!=len(rows) or not 1<=len(rows)<=2 or any(len(r['groups'])>2048 for r in rows):return []
    before=records(root);proposed=records(other);bo=sum(map(len,bs[:i]));co=sum(map(len,cs[:i]));a=before[bo:bo+len(bs[i])];b=proposed[co:co+len(cs[i])]
    old_clocks={id(m):Counter((r['key'],r['voice'],r['grace']) for r in rs) for m,rs in zip(bm,before)}
    changes=[];part=root.find('part')
    if len(b)==len(a)+1:
        sites=insertion_sites([signature(r) for r in a],[signature(r) for r in b])
        if len(sites)!=1:return []
        j=sites[0]
        # Two exact neighbor clocks locate the edit; the inserted bar must
        # contain at least two physically distinct note columns, not rests.
        if any(r['grace'] for r in b[j]) or len(b[j])>128 or sum(pitches(b[j]).values())<2:return []
        from .relation_ensemble import flow_health
        if not flow_health(other)[co+j]['full']:return []
        from .relation_measure_joint import context_rows,head_witness,stem_witness
        from .relation_measure_realign import hollow_on_line,traced_stem
        stems={s['id']:s for s in graph['stems']};ctx=context_rows(other)[co+j][1];bounds=rows[0]['bounds']
        if any(crossing(image,t,x)<.95 for t in ts for x in bounds[j:j+3]):return []
        for row,t in zip(rows,ts):
            s=row['space_px'];heads=[h for g in row['groups'] for h in g.get('heads',[])]
            if any(abs(h['xy'][0]-x)<.8*s for h in heads for x in bounds[j:j+3]):return []
            gs=[g for g in row['groups'] if bounds[j]<g['x']<bounds[j+1]]
            if not gs:continue
            if len(gs)<2 or any(not g.get('heads') or g.get('grace') or g.get('beams') or g.get('flags') or g.get('dotted') or g.get('tuplet_ratio') or g['duration'] not in (480,960) for g in gs):return []
            if any(not (stem_witness(g,row,stems,image) or traced_stem(g,row,stems,image)) for g in gs):return []
            if any(not (head_witness(h,row,t,ctx.get(row['staff'],{}),image) or hollow_on_line(h,row,t,ctx.get(row['staff'],{}),image)) for g in gs for h in g['heads']):return []
        # Candidate durations are expressed in its inherited divisions;
        # convert to the primary's local divisions without changing old ones.
        division=1
        for m in bm[:bo+j+1]:
            for attr in m.findall('attributes'):division=int(attr.findtext('divisions',str(division)))
        cdivision=1
        for m in cm[:co+j+1]:
            for attr in m.findall('attributes'):cdivision=int(attr.findtext('divisions',str(cdivision)))
        new=copy.deepcopy(cs[i][j])
        if any(n.tag not in ('note','backup','forward','barline') for n in new):return []
        for d in new.findall('.//duration'):
            value=Fraction(int(d.text)*division,cdivision)
            if value.denominator!=1:return []
            d.text=str(value.numerator)
        voices={}
        for cr,br in ((b[j-1],a[j-1]),(b[j+1],a[j])):
            for r in cr:
                hits=[v for v in br if v['key']==r['key'] and v['grace']==r['grace']]
                if len(hits)==1:voices.setdefault((r['staff'],r['voice']),set()).add(hits[0]['voice'])
        for n in new.findall('note'):
            key=(int(n.findtext('staff','1')),n.findtext('voice','1'));v=voices.get(key,set())
            if len(v)!=1:return []
            n.find('voice').text=next(iter(v))
        part.insert(list(part).index(bs[i][j]),new)
        changes.append({'method':'unique_anchored_missing_musical_bar','system':sid,'measure':bo+j+1,'added_notes':len(new.findall('note')),'neighbor_clocks_preserved':True})
    elif i==len(ids)-1 and len(a)==len(b)+1 and len(a)>=4 and len(rows)==2:
        tail=bs[i][-1];kept=bs[i][-2]
        if tail.find('attributes/key') is None or kept.findtext('barline/bar-style') not in ('light-light','light-heavy'):return []
        if any(r['grace'] for r in a[-1]+a[-2]) or not pitches(a[-2]) or pitches(a[-1],True)!=pitches(a[-2],True):return []
        if any(r['onset']!=0 for r in a[-1]+a[-2]) or {r['duration'] for r in a[-1]+a[-2]}!={a[-2][0]['duration']}:return []
        if any(pitches(a[k])!=pitches(b[k+1]) for k in (-4,-3)):return []
        if pitches(a[-2])-pitches(b[-1]):return []
        x=rows[0]['bounds'][-1]
        if any(crossing(image,t,x)<.95 for t in ts):return []
        for row in rows:
            s=row['space_px'];nodes=[n for n in row['nodes'] if n['xy'][0]>x+.2*s]
            keys=[n for n in nodes if n['class'] in (8,9) and n.get('confidence',0)>=.8 and n['xy'][0]<x+5*s]
            if len(keys)<2 or len({n['class'] for n in keys})!=1:return []
            if any(g['x']>x for g in row['groups']):return []
            if any(n['class'] not in (8,9,10) and n.get('confidence',0)>.8 for n in nodes):return []
        # The photographed trailing key is retained after the last notes. It
        # has no musical time and must not clone the preceding chord.
        for attr in tail.findall('attributes'):kept.append(copy.deepcopy(attr))
        part.remove(tail)
        changes.append({'method':'terminal_key_signature_duplicate_chord','system':sid,'removed_measure':bo+len(a),'retained_measure_clocks_preserved':True,'trailing_key_preserved':True})
    if changes:
        for m,rs in zip(root.findall('part/measure'),records(root)):
            if id(m) in old_clocks and old_clocks[id(m)]!=Counter((r['key'],r['voice'],r['grace']) for r in rs):raise ValueError('Local count recovery changed a retained measure clock')
        for number,m in enumerate(root.findall('part/measure'),1):m.set('number',str(number))
    return changes
